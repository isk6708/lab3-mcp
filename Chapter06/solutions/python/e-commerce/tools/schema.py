from pydantic import BaseModel

class AddCartInputModel(BaseModel):
    cart_id: int
    product_id: int
    quantity: int

class AddInputModel(BaseModel):
    a: float
    b: float

class CategoryModel(BaseModel):
    name: str
    description: str

class CustomerModel(BaseModel):
    id: int
    name: str
    email: str

class ProductModel(BaseModel):
    id: int
    name: str
    price: float
    description: str

class CartItemModel(BaseModel):
    cart_id: int
    product_id: int
    quantity: int

class OrderModel(BaseModel):
    order_id: int
    customer_id: int
    quantity: int
    total_price: float

class GetOrderInputModel(BaseModel):
    # 0 = return orders for every customer
    customer_id: int = 0

class GetProductInputModel(BaseModel):
    product_id: int

# --- Input models added for the e-commerce fix ---------------------------

class GetCartItemsInputModel(BaseModel):
    # 0 = return items from every cart
    cart_id: int = 0

class GetOrderByIdInputModel(BaseModel):
    order_id: int

class PlaceOrderInputModel(BaseModel):
    # order_id is generated by the server, so the caller no longer supplies it
    customer_id: int
    quantity: int
    total_price: float
